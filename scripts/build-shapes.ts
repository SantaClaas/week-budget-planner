// Builds docs/design/m3-shapes.css: Google's Material 3 Expressive shape library as CSS shape() values.
//
//   node scripts/build-shapes.ts
//
// The shapes are defined in Kotlin, in androidx's MaterialShapes.kt, on top of the graphics-shapes
// library (RoundedPolygon). Rather than redrawing them, this script compiles Google's own sources at a
// pinned commit, prints every normalized shape's cubic curves, and writes each one as
//   --shape-<name>: shape(from …, curve to … with … / …, …, close)
// in a 0–100% box. Use one with `clip-path: var(--shape-cookie-9)`.
//
// Needs Java and network access to github.com. The Kotlin compiler and the sources are cached in
// .cache/material-shapes/ (git-ignored). The files in scripts/material-shapes/ are small stand-ins for
// the Android and Compose types the sources import, plus the program that prints the curves.

import { execFileSync } from "node:child_process";
import { mkdir, readFile, writeFile, readdir, copyFile, access } from "node:fs/promises";

const ANDROIDX_COMMIT = "8bd26e227f5a44199493cccb61b1e118f2574d62";
const KOTLIN_VERSION = "2.1.0";

const root = new URL("../", import.meta.url);
const cache = new URL(".cache/material-shapes/", root);
const sources = new URL(`androidx-${ANDROIDX_COMMIT}/`, cache);
const build = new URL("build/", cache);
const output = new URL("docs/design/m3-shapes.css", root);

const raw = (path: string): string =>
  `https://raw.githubusercontent.com/androidx/androidx/${ANDROIDX_COMMIT}/${path}`;
const SHAPES_DIR = "graphics/graphics-shapes/src/commonMain/kotlin/androidx/graphics/shapes";
// FloatMapping.kt and Morph are only needed for morphing between shapes, not for static outlines.
const GRAPHICS_SHAPES = [
  "CornerRounding",
  "Cubic",
  "Features",
  "Point",
  "RoundedPolygon",
  "Shapes",
  "Utils",
];
const MATERIAL_SHAPES =
  "compose/material3/material3/src/commonMain/kotlin/androidx/compose/material3/MaterialShapes.kt";

await mkdir(sources, { recursive: true });
await mkdir(build, { recursive: true });

// 1. Kotlin compiler
const kotlinc = new URL(`kotlinc-${KOTLIN_VERSION}/kotlinc/bin/kotlinc`, cache);
if (!(await exists(kotlinc))) {
  const zip = new URL(`kotlin-compiler-${KOTLIN_VERSION}.zip`, cache);
  await download(
    `https://github.com/JetBrains/kotlin/releases/download/v${KOTLIN_VERSION}/kotlin-compiler-${KOTLIN_VERSION}.zip`,
    zip,
    "binary",
  );
  execFileSync("unzip", [
    "-q",
    "-o",
    zip.pathname,
    "-d",
    new URL(`kotlinc-${KOTLIN_VERSION}/`, cache).pathname,
  ]);
}

// 2. Google's sources at the pinned commit
for (const name of GRAPHICS_SHAPES) {
  const target = new URL(`${name}.kt`, sources);
  if (!(await exists(target))) await download(raw(`${SHAPES_DIR}/${name}.kt`), target);
}
const materialShapes = new URL("MaterialShapes.kt", sources);
if (!(await exists(materialShapes))) await download(raw(MATERIAL_SHAPES), materialShapes);

// 3. Assemble: graphics-shapes as is, MaterialShapes reduced to its companion object's shape builders
for (const file of await readdir(build))
  if (file.endsWith(".kt")) await writeFile(new URL(file, build), "");
for (const name of GRAPHICS_SHAPES)
  await copyFile(new URL(`${name}.kt`, sources), new URL(`${name}.kt`, build));
for (const file of await readdir(new URL("scripts/material-shapes/", root))) {
  await copyFile(new URL(`scripts/material-shapes/${file}`, root), new URL(file, build));
}
await writeFile(
  new URL("MaterialShapes.kt", build),
  extractMaterialShapes(await readFile(materialShapes, "utf8")),
);

// 4. Compile and print the curves
const jar = new URL("shapes.jar", build).pathname;
const kotlinFiles = (await readdir(build))
  .filter((file) => file.endsWith(".kt"))
  .map((file) => new URL(file, build).pathname);
execFileSync(kotlinc.pathname, [...kotlinFiles, "-nowarn", "-include-runtime", "-d", jar], {
  stdio: "inherit",
});
const cubics = readCubics(
  JSON.parse(
    execFileSync("java", ["-jar", jar], { encoding: "utf8", stdio: ["ignore", "pipe", "ignore"] }),
  ),
);

// 5. CSS
const percent = (value: number): string => `${Number((value * 100).toFixed(2)).toString()}%`;
const point = (x: number, y: number): string => `${percent(x)} ${percent(y)}`;
const lines = [...cubics].map(([name, curves]) => {
  const [first] = curves;
  if (first === undefined) throw new Error(`The shape ${name} has no curves.`);
  const segments = curves.map(
    ({ control0X, control0Y, control1X, control1Y, endX, endY }) =>
      `curve to ${point(endX, endY)} with ${point(control0X, control0Y)} / ${point(control1X, control1Y)}`,
  );
  return `  --shape-${name}: shape(from ${point(first.startX, first.startY)}, ${segments.join(", ")}, close);`;
});
const css = `/* Material 3 Expressive shape library, generated by scripts/build-shapes.ts. Don't edit by hand.
   Source: androidx MaterialShapes.kt and graphics-shapes at commit ${ANDROIDX_COMMIT}.
   Each shape fills a 0–100% box. Use it with clip-path, for example clip-path: var(--shape-cookie-9).
   The shapes are design tokens, so they sit in the theme layer (see m3-tokens.css). */
@layer theme {
  :root {
${lines.map((line) => `  ${line}`).join("\n")}
  }
}
`;
await writeFile(output, css);
console.log(
  `wrote docs/design/m3-shapes.css with ${lines.length.toString()} shapes (${css.length.toString()} bytes)`,
);

/** One cubic Bézier curve, as the Kotlin program prints it: [x0, y0, c0x, c0y, c1x, c1y, x1, y1]. */
type Cubic = {
  startX: number;
  startY: number;
  control0X: number;
  control0Y: number;
  control1X: number;
  control1Y: number;
  endX: number;
  endY: number;
};

/** Checks the Kotlin program's output: every shape name maps to a list of 8 numbers per curve. */
function readCubics(value: unknown): Map<string, Cubic[]> {
  if (typeof value !== "object" || value === null)
    throw new Error("The shape program printed no shapes.");
  const shapes = new Map<string, Cubic[]>();
  for (const [name, curves] of Object.entries(value)) {
    if (!Array.isArray(curves)) throw new Error(`The shape ${name} isn't a list of curves.`);
    shapes.set(
      name,
      curves.map((curve: unknown) => {
        const at = (index: number): number => {
          const item: unknown =
            Array.isArray(curve) && curve.length === 8 ? curve[index] : undefined;
          if (typeof item !== "number")
            throw new Error(`A curve of ${name} isn't 8 numbers: ${JSON.stringify(curve)}`);
          return item;
        };
        return {
          startX: at(0),
          startY: at(1),
          control0X: at(2),
          control0Y: at(3),
          control1X: at(4),
          control1Y: at(5),
          endX: at(6),
          endY: at(7),
        };
      }),
    );
  }
  return shapes;
}

/** Keeps the companion object's shape builders and helpers, minus the Compose-only parts. */
function extractMaterialShapes(source: string): string {
  const start = source.indexOf("public companion object {");
  const end = source.lastIndexOf("}", source.lastIndexOf("}") - 1);
  if (start < 0 || end < start)
    throw new Error("MaterialShapes.kt changed shape; update extractMaterialShapes()");
  const body = source.slice(source.indexOf("{", start) + 1, end);
  return `package androidx.compose.material3
import androidx.compose.ui.geometry.Offset
import androidx.compose.ui.graphics.Matrix
import androidx.graphics.shapes.CornerRounding
import androidx.graphics.shapes.RoundedPolygon
import androidx.graphics.shapes.TransformResult
import androidx.graphics.shapes.circle
import androidx.graphics.shapes.rectangle
import androidx.graphics.shapes.star
import kotlin.math.PI
import kotlin.math.atan2
import kotlin.math.cos
import kotlin.math.sin
fun <T, R> List<T>.fastMap(f: (T) -> R): List<R> = map(f)
// Same as androidx.compose.material3.internal.transformed: maps every point through the matrix.
fun RoundedPolygon.transformed(m: Matrix): RoundedPolygon =
    transformed { x, y -> m.map(Offset(x, y)).let { TransformResult(it.x, it.y) } }
object MaterialShapes {
${body.replaceAll("@ExperimentalMaterial3ExpressiveApi", "").replaceAll("public val ", "val ")}
}
`;
}

async function download(url: string, target: URL, mode: "text" | "binary" = "text"): Promise<void> {
  const response = await fetch(url);
  if (!response.ok) throw new Error(`Couldn't download ${url}: ${response.status.toString()}`);
  await writeFile(
    target,
    mode === "binary" ? Buffer.from(await response.arrayBuffer()) : await response.text(),
  );
  console.log(`downloaded ${url}`);
}

async function exists(url: URL): Promise<boolean> {
  try {
    await access(url);
    return true;
  } catch {
    return false;
  }
}
